// ---------- Render results ----------
function renderResults(data) {
  // Concept summary
  $("concept-summary-text").textContent = data.conceptSummary || "";

  // Warnings
  const warnings = data.warnings || [];
  if (warnings.length) {
    $("warnings-banner").classList.remove("hidden");
    $("warnings-list").innerHTML = warnings.map((w) => `<li>${escapeHtml(w)}</li>`).join("");
  } else {
    $("warnings-banner").classList.add("hidden");
  }

  // Roadmap, grouped by phase
  const phases = ["Setup", "Build-out", "Pre-opening"];
  const phaseClass = { "Setup": "phase-setup", "Build-out": "phase-buildout", "Pre-opening": "phase-preopening" };
  const grouped = {};
  phases.forEach((p) => (grouped[p] = []));
  (data.roadmap || []).forEach((item) => {
    if (grouped[item.phase]) grouped[item.phase].push(item);
    else (grouped["Setup"] ||= []).push(item);
  });

  const rc = $("roadmap-container");
  rc.innerHTML = "";
  phases.forEach((phase) => {
    const items = grouped[phase];
    if (!items.length) return;
    const section = document.createElement("div");
    section.innerHTML = `
      <h4 class="font-serif-display text-lg font-semibold text-stone-700 mb-3 uppercase tracking-wide text-xs">${escapeHtml(t(`phase.${phase}`))}</h4>
      <div class="space-y-3">
        ${items.map((it) => `
          <div class="menu-card border border-stone-200 rounded-lg p-4 shadow-sm ${phaseClass[phase]}">
            <div class="font-semibold text-stone-900">${escapeHtml(it.item || "")}</div>
            <div class="text-sm text-stone-600 mt-1">${escapeHtml(it.whatItIs || "")}</div>
            <div class="flex flex-wrap gap-x-4 gap-y-1 text-xs text-stone-500 mt-2">
              ${it.fee ? `<span><span class="font-medium text-stone-600">${escapeHtml(t("results.fee"))}:</span> ${escapeHtml(it.fee)}</span>` : ""}
              ${it.timeline ? `<span><span class="font-medium text-stone-600">${escapeHtml(t("results.timeline"))}:</span> ${escapeHtml(it.timeline)}</span>` : ""}
              ${it.agency ? `<span><span class="font-medium text-stone-600">${escapeHtml(t("results.agency"))}:</span> ${escapeHtml(it.agency)}</span>` : ""}
            </div>
          </div>
        `).join("")}
      </div>`;
    rc.appendChild(section);
  });

  // Prep sheet
  const ps = data.prepSheet || {};
  const pc = $("prep-container");
  pc.innerHTML = `
    <div>
      <div class="text-xs uppercase tracking-wide text-stone-500 font-semibold">${escapeHtml(t("results.nextInteraction"))}</div>
      <div class="font-serif-display text-xl font-semibold text-stone-900 mt-1">${escapeHtml(ps.interactionName || "")}</div>
      ${ps.location ? `<div class="text-sm text-stone-600 mt-1">📍 ${escapeHtml(ps.location)}</div>` : ""}
    </div>
    ${section("results.whatToBring", ps.whatToBring)}
    ${section("results.theyWillAsk", ps.theyWillAsk)}
    ${section("results.youShouldAsk", ps.youShouldAsk)}
    ${section("results.keyTerms", ps.keyTermsEnglish, true)}
    ${ps.whatGoodLooksLike ? `<div><div class="text-xs uppercase tracking-wide text-stone-500 font-semibold mb-1">${escapeHtml(t("results.whatGoodLooksLike"))}</div><div class="text-sm text-stone-700">${escapeHtml(ps.whatGoodLooksLike)}</div></div>` : ""}
    ${ps.ifItGoesBadly ? `<div><div class="text-xs uppercase tracking-wide text-stone-500 font-semibold mb-1">${escapeHtml(t("results.ifItGoesBadly"))}</div><div class="text-sm text-stone-700">${escapeHtml(ps.ifItGoesBadly)}</div></div>` : ""}
  `;
}

function section(titleKey, items, mono = false) {
  if (!items || !items.length) return "";
  return `<div>
    <div class="text-xs uppercase tracking-wide text-stone-500 font-semibold mb-1">${escapeHtml(t(titleKey))}</div>
    <ul class="list-disc pl-5 space-y-1 text-sm text-stone-700 ${mono ? "font-mono" : ""}">${items.map((i) => `<li>${escapeHtml(i)}</li>`).join("")}</ul>
  </div>`;
}

function escapeHtml(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

